export const locales = { pl: "pl-PL", en: "en-GB", fr: "fr-FR" };
export function workCount(n: number, lang: Language) {
  const category = new Intl.PluralRules(locales[lang]).select(n);
  const noun =
    lang === "pl"
      ? category === "one"
        ? "praca"
        : category === "few"
          ? "prace"
          : "prac"
      : lang === "fr"
        ? n === 1
          ? "œuvre"
          : "œuvres"
        : n === 1
          ? "work"
          : "works";
  return `${String(n).padStart(2, "0")} ${noun}`;
}
